# Import all necessary libraries
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# Scikit-learn imports
from sklearn.model_selection import train_test_split, cross_val_score, GridSearchCV
from sklearn.preprocessing import StandardScaler, LabelEncoder, OneHotEncoder
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline

# Regression models
from sklearn.linear_model import LinearRegression
from sklearn.tree import DecisionTreeRegressor
from sklearn.ensemble import RandomForestRegressor, GradientBoostingRegressor

# Classification models
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.ensemble import GradientBoostingClassifier

# Metrics
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, confusion_matrix, classification_report

# For warnings
import warnings
warnings.filterwarnings('ignore')

print("✅ All imports completed successfully!")

df = pd.read_csv('student-por.csv', sep=';')
print(f"✅ Dataset loaded: {df.shape[0]} rows, {df.shape[1]} columns")
print("\nFirst 5 rows:")
df.head()

# Create pass/fail target variable
df['pass_fail'] = (df['G3'] >= 10).astype(int)

# Define features and targets
# IMPORTANT: Excluding G1 and G2 to avoid data leakage
features_to_drop = ['G1', 'G2', 'G3', 'pass_fail']
X = df.drop(columns=features_to_drop)
y_reg = df['G3']  # For regression
y_clf = df['pass_fail']  # For classification

print(f"✅ Features: {X.shape[1]} columns")
print(f"✅ Regression target: {y_reg.name}")
print(f"✅ Classification target: {y_clf.name}")
print(f"\n📊 Pass/Fail Distribution:")
print(df['pass_fail'].value_counts())
print(f"Pass rate: {df['pass_fail'].mean()*100:.1f}%")

# Identify categorical and numerical columns
categorical_cols = X.select_dtypes(include=['object']).columns.tolist()
numerical_cols = X.select_dtypes(include=['int64', 'float64']).columns.tolist()

print(f"✅ Categorical features ({len(categorical_cols)}):")
print(categorical_cols)
print(f"\n✅ Numerical features ({len(numerical_cols)}):")
print(numerical_cols)

# Create preprocessing pipeline
preprocessor = ColumnTransformer(
    transformers=[
        ('num', StandardScaler(), numerical_cols),
        ('cat', OneHotEncoder(drop='first', sparse_output=False), categorical_cols)
    ])

print("✅ Preprocessor created successfully!")
print(f"   - Numerical features will be scaled")
print(f"   - Categorical features will be one-hot encoded")

# Split the data
X_train, X_test, y_reg_train, y_reg_test = train_test_split(
    X, y_reg, test_size=0.2, random_state=42
)
_, _, y_clf_train, y_clf_test = train_test_split(
    X, y_clf, test_size=0.2, random_state=42
)

print(f"✅ Data split complete!")
print(f"   - Training set: {X_train.shape[0]} samples")
print(f"   - Test set: {X_test.shape[0]} samples")

# Regression models
reg_models = {
    'Linear Regression': LinearRegression(),
    'Decision Tree': DecisionTreeRegressor(random_state=42),
    'Random Forest': RandomForestRegressor(random_state=42, n_estimators=100),
    'Gradient Boosting': GradientBoostingRegressor(random_state=42)
}

# Train and evaluate regression models
reg_results = {}
reg_pipelines = {}

print("🔄 Training Regression Models...\n")

for name, model in reg_models.items():
    # Create pipeline
    pipeline = Pipeline([
        ('preprocessor', preprocessor),
        ('regressor', model)
    ])

    # Train
    pipeline.fit(X_train, y_reg_train)
    reg_pipelines[name] = pipeline

    # Predict
    y_pred = pipeline.predict(X_test)

    # Evaluate
    mae = mean_absolute_error(y_reg_test, y_pred)
    rmse = np.sqrt(mean_squared_error(y_reg_test, y_pred))
    r2 = r2_score(y_reg_test, y_pred)

    reg_results[name] = {'MAE': mae, 'RMSE': rmse, 'R2': r2}

    print(f"📊 {name}:")
    print(f"   MAE: {mae:.3f}")
    print(f"   RMSE: {rmse:.3f}")
    print(f"   R²: {r2:.3f}")
    print("-" * 35)

# Store the best regression model (Random Forest)
best_reg_model = reg_pipelines['Random Forest']
print(f"\n✅ Best regression model: Random Forest (R² = {reg_results['Random Forest']['R2']:.3f})")

clf_models = {
    'Logistic Regression': LogisticRegression(random_state=42, solver='liblinear'),
    'Decision Tree': DecisionTreeClassifier(random_state=42),
    'Random Forest': RandomForestClassifier(random_state=42, n_estimators=100),
    'Gradient Boosting': GradientBoostingClassifier(random_state=42)
}

# Train and evaluate classification models
clf_results = {}
clf_pipelines = {}

print("🔄 Training Classification Models...\n")

for name, model in clf_models.items():
    # Create pipeline
    pipeline = Pipeline([
        ('preprocessor', preprocessor),
        ('classifier', model)
    ])

    # Train
    pipeline.fit(X_train, y_clf_train)
    clf_pipelines[name] = pipeline

    # Predict
    y_pred = pipeline.predict(X_test)

    # Evaluate
    accuracy = accuracy_score(y_clf_test, y_pred)
    precision = precision_score(y_clf_test, y_pred, zero_division=0)
    recall = recall_score(y_clf_test, y_pred, zero_division=0)
    f1 = f1_score(y_clf_test, y_pred, zero_division=0)

    clf_results[name] = {
        'Accuracy': accuracy,
        'Precision': precision,
        'Recall': recall,
        'F1': f1
    }

    print(f"📊 {name}:")
    print(f"   Accuracy: {accuracy:.3f}")
    print(f"   Precision: {precision:.3f}")
    print(f"   Recall: {recall:.3f}")
    print(f"   F1-Score: {f1:.3f}")
    print("-" * 35)

# Store the best classification model (e.g., based on Accuracy)
best_clf_model_name = max(clf_results, key=lambda k: clf_results[k]['Accuracy'])
best_clf_model = clf_pipelines[best_clf_model_name]
print(f"\n✅ Best classification model: {best_clf_model_name} (Accuracy = {clf_results[best_clf_model_name]['Accuracy']:.3f})")

# Create comparison charts
fig, axes = plt.subplots(1, 2, figsize=(15, 6))

# Regression results
reg_df = pd.DataFrame(reg_results).T
reg_df[['R2']].plot(kind='bar', ax=axes[0], color='skyblue', legend=False)
axes[0].set_title('Regression Model Performance (R² Score)', fontsize=14)
axes[0].set_ylabel('R² Score')
axes[0].set_xlabel('Model')
axes[0].set_ylim(0, 1)
axes[0].grid(True, alpha=0.3)
for i, v in enumerate(reg_df['R2']):
    axes[0].text(i, v + 0.02, f'{v:.3f}', ha='center', fontweight='bold')

# Classification results
clf_df = pd.DataFrame(clf_results).T
clf_df[['Accuracy', 'F1']].plot(kind='bar', ax=axes[1])
axes[1].set_title('Classification Model Performance', fontsize=14)
axes[1].set_ylabel('Score')
axes[1].set_xlabel('Model')
axes[1].set_ylim(0, 1)
axes[1].grid(True, alpha=0.3)
axes[1].legend(loc='lower right')

plt.tight_layout()
plt.show()

# Extract feature importances from Random Forest
rf_regressor = best_reg_model.named_steps['regressor']

# Get feature names after preprocessing
preprocessor.fit(X_train)
feature_names = (numerical_cols +
                 list(preprocessor.named_transformers_['cat'].get_feature_names_out(categorical_cols)))

importances = rf_regressor.feature_importances_

# Create importance DataFrame
importance_df = pd.DataFrame({
    'feature': feature_names,
    'importance': importances
}).sort_values('importance', ascending=False)

# Plot top 15 features
plt.figure(figsize=(12, 8))
top_features = importance_df.head(15)
plt.barh(top_features['feature'], top_features['importance'], color='teal')
plt.xlabel('Feature Importance', fontsize=12)
plt.title('Top 15 Features for Predicting Student Grades', fontsize=14)
plt.gca().invert_yaxis()
plt.tight_layout()
plt.show()

print("\n📊 Top 10 Most Important Features:")
print(top_features[['feature', 'importance']].head(10).to_string(index=False))

# Confusion matrix for best classifier
y_pred_best = best_clf_model.predict(X_test)
cm = confusion_matrix(y_clf_test, y_pred_best)

plt.figure(figsize=(8, 6))
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues',
            xticklabels=['Fail (0)', 'Pass (1)'],
            yticklabels=['Fail (0)', 'Pass (1)'])
plt.title('Confusion Matrix - Random Forest Classifier', fontsize=14)
plt.xlabel('Predicted', fontsize=12)
plt.ylabel('Actual', fontsize=12)
plt.show()

print("\n📋 Detailed Classification Report:")
print(classification_report(y_clf_test, y_pred_best, target_names=['Fail', 'Pass']))

